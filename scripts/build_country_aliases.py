"""Regenerate config/country_aliases.yaml from the UN's own member-state lists (zh and en pages), aligned by the
flag code each country card carries (class "flags-<code>"). Usage:
    curl -sL https://www.un.org/zh/about-us/member-states -o un_zh.html
    curl -sL https://www.un.org/en/about-us/member-states -o un_en.html
    python scripts/build_country_aliases.py un_zh.html un_en.html > config/country_aliases.yaml
The short forms at the end are written by hand; each names the UN entry it abbreviates."""
import re
import sys

CARD = re.compile(r'flags flags-([a-z]{2,3})"[^<]*</div>\s*</div>\s*<h2 class="mb-0">(.*?)</h2>', re.S)
SHORT = [  # (UN code, extra English forms, extra Chinese forms)
    ("us", ["us", "u.s.", "usa", "united states", "america"], ["美国"]),
    ("gb", ["uk", "u.k.", "britain", "united kingdom", "great britain"], ["英国"]),
    ("ru", ["russia"], ["俄罗斯"]),
    ("cn", ["china", "people's republic of china", "prc"], ["中华人民共和国"]),
    ("kr", ["south korea"], ["韩国"]),
    ("kp", ["north korea"], ["朝鲜"]),
    ("ir", ["iran"], ["伊朗"]),
    ("sy", ["syria"], ["叙利亚"]),
    ("vn", ["vietnam"], ["越南"]),
    ("la", ["laos"], ["老挝"]),
    ("ve", ["venezuela"], ["委内瑞拉"]),
    ("bo", ["bolivia"], ["玻利维亚"]),
    ("tz", ["tanzania"], ["坦桑尼亚"]),
    ("md", ["moldova"], ["摩尔多瓦"]),
    ("tr", ["turkey", "türkiye", "turkiye"], ["土耳其"]),
    ("cz", ["czech republic", "czechia"], ["捷克"]),
    ("nl", ["netherlands", "the netherlands"], ["荷兰"]),
    ("cd", ["dr congo", "drc", "democratic republic of the congo", "congo-kinshasa"], ["刚果（金）", "刚果(金)"]),
    ("cg", ["republic of the congo", "congo-brazzaville"], ["刚果（布）", "刚果(布)"]),
]


def cards(path):
    t = open(path, encoding="utf-8").read()
    return {code: re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", name)).strip() for code, name in CARD.findall(t)}


zh, en = cards(sys.argv[1]), cards(sys.argv[2])
short = {c: (e, z) for c, e, z in SHORT}
print("# GENERATED by scripts/build_country_aliases.py from https://www.un.org/zh/about-us/member-states and")
print("# https://www.un.org/en/about-us/member-states (fetched 2026-11-01), aligned by each card's flag code.")
print("# basis official = the UN's own zh/en names; short_form = a hand-written abbreviation of that UN entry.")
print("aliases:")
for code in sorted(set(zh) | set(en)):
    z, e = zh.get(code), en.get(code)
    if z and e:
        print(f'  - {{zh: "{z}", en: ["{e.lower()}"], basis: official, ref: "un.org member states, flags-{code}"}}')
    if code in short:
        es, zs = short[code]
        for zz in zs:
            ens = ", ".join(f'"{x}"' for x in ([e.lower()] if e else []) + es)
            ref = f"short form of UN {e or z} (flags-{code})"
            print(f'  - {{zh: "{zz}", en: [{ens}], basis: short_form, ref: "{ref}"}}')
missing = sorted(set(zh) ^ set(en))
print(f"# flag codes on one page only: {missing}")
